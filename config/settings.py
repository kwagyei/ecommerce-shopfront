"""Django settings for shopfront.

Every environment-specific value is read from the environment, with defaults that
are safe for local development only. Nothing secret is committed; see .env.example.
"""

import os
from pathlib import Path

import dj_database_url
from dotenv import load_dotenv

from core.checks import DEV_SECRET_KEY

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(BASE_DIR / ".env")


def env_bool(name: str, default: bool = False) -> bool:
    return os.environ.get(name, str(default)).strip().lower() in {"1", "true", "yes", "on"}


def env_list(name: str) -> list[str]:
    return [item.strip() for item in os.environ.get(name, "").split(",") if item.strip()]


# Insecure default so `manage.py runserver` works out of the box. A deploy still using
# it fails `check --deploy` in build.sh (core/checks.py), so production must set its own.
SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY", DEV_SECRET_KEY)
DEBUG = env_bool("DJANGO_DEBUG", False)
ALLOWED_HOSTS = env_list("DJANGO_ALLOWED_HOSTS") or (["*"] if DEBUG else [])
CSRF_TRUSTED_ORIGINS = env_list("DJANGO_CSRF_TRUSTED_ORIGINS")

# Render provides this; it lets the app trust its own external hostname.
if render_host := os.environ.get("RENDER_EXTERNAL_HOSTNAME"):
    ALLOWED_HOSTS.append(render_host)
    CSRF_TRUSTED_ORIGINS.append(f"https://{render_host}")

